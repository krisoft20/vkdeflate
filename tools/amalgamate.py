#!/usr/bin/env python3
"""Builds single_include/vkdeflate.h from src/, and prebuilt/tile_spv.inc from src/tile.comp.

The declarations of gdeflate.h and vkdeflate.h come first; under VKDEFLATE_IMPLEMENTATION
follow gdeflate.cpp and vkdeflate.cpp with the compiled shader inlined, so a user needs neither
glslc nor this repository's build. prebuilt/tile_spv.inc is the same compiled shader for a build
of this repository on a machine without glslc; its first line carries the hash of tile.comp.

    python tools/amalgamate.py [--glslc path] [--out single_include/vkdeflate.h]
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEEP = {'WIN32_LEAN_AND_MEAN', 'NOMINMAX'}

HEAD = """// vkdeflate.h - GDeflate 1.0 decoder for Vulkan compute, with a CPU reference decoder, in one file.
// Generated by tools/amalgamate.py from src/; edit the sources, not this file.
//
// In exactly one source file:
//
//     #define VKDEFLATE_IMPLEMENTATION
//     #include "vkdeflate.h"
//
// and plain #include "vkdeflate.h" everywhere else. Needs C++17 and the Vulkan headers; the compute
// shader is inside as SPIR-V. A device needs Vulkan 1.3 with shaderInt64, shaderInt8,
// storageBuffer8BitAccess, bufferDeviceAddress, vulkanMemoryModel and subgroup operations in compute.
//
//     gdeflate::decompress(stream, n, out, size, err)                     CPU, any machine
//     vkdeflate::describe(stream, header_bytes, n, tiles, out_size, err)  stream header -> tile table
//     vkdeflate::attach(instance, phys, device, vkGetInstanceProcAddr, {}, err)
//     vkdeflate::record(ctx, cmd, {src, tiles, dst, status, count})       one dispatch in your command buffer
//     vkdeflate::create({}, err) / vkdeflate::decompress(ctx, ...)        standalone: own device, host memory
//
"""


def read(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n')


def body(text):
    lines = text.split('\n')
    i = 0
    while i < len(lines) and (lines[i].startswith('//') or not lines[i].strip()):
        i += 1
    return '\n'.join(lines[i:]).strip('\n') + '\n'


def drop(text, *lines):
    for line in lines:
        if line + '\n' not in text:
            sys.exit('amalgamate: line not found: ' + line)
        text = text.replace(line + '\n', '', 1)
    return text


def swap(text, old, new):
    if old not in text:
        sys.exit('amalgamate: text not found: ' + old.strip())
    return text.replace(old, new, 1)


def find_glslc(arg):
    if arg:
        return arg
    cache = os.path.join(ROOT, 'build', 'CMakeCache.txt')
    if os.path.exists(cache):
        with open(cache, encoding='utf-8', errors='replace') as f:
            for line in f:
                if line.startswith('GLSLC:'):
                    return line.split('=', 1)[1].strip()
    return 'glslc'


def spirv(glslc):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, 'tile_spv.inc')
        subprocess.check_call([glslc, '--target-env=vulkan1.3', '-O', '-mfmt=c',
                               os.path.join(ROOT, 'src', 'tile.comp'), '-o', out])
        with open(out, encoding='utf-8') as f:
            return f.read().strip()


def tile_hash():
    with open(os.path.join(ROOT, 'src', 'tile.comp'), 'rb') as f:
        return hashlib.sha256(f.read().replace(b'\r', b'')).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--glslc')
    ap.add_argument('--out', default=os.path.join(ROOT, 'single_include', 'vkdeflate.h'))
    a = ap.parse_args()

    decl = drop(body(read('src/gdeflate.h')), '#pragma once') + '\n' + drop(body(read('src/vkdeflate.h')), '#pragma once')
    cpu = drop(body(read('src/gdeflate.cpp')), '#include "gdeflate.h"')
    gpu = drop(body(read('src/vkdeflate.cpp')), '#define _CRT_SECURE_NO_WARNINGS', '#define VK_NO_PROTOTYPES',
               '#include "gdeflate.h"', '#include "vkdeflate.h"')
    for m in sorted(KEEP):
        gpu = swap(gpu, '#define %s\n' % m, '#ifndef %s\n#define %s\n#endif\n' % (m, m))
    spv = spirv(find_glslc(a.glslc))
    gpu = swap(gpu, '#include "tile_spv.inc"\n', spv + '\n')

    macros = []
    for m in re.findall(r'^#define (\w+)', cpu + gpu, re.M):
        if m not in KEEP and m not in macros:
            macros.append(m)

    lic = ''.join(('// ' + line).rstrip() + '\n' for line in read('LICENSE').strip('\n').split('\n'))
    text = (HEAD + lic + '\n#ifndef VKDEFLATE_H\n#define VKDEFLATE_H\n\n' + decl + '\n#endif\n\n'
            '#if defined(VKDEFLATE_IMPLEMENTATION) && !defined(VKDEFLATE_IMPLEMENTATION_DONE)\n'
            '#define VKDEFLATE_IMPLEMENTATION_DONE\n\n'
            '#if defined(_MSC_VER)\n#pragma warning(push)\n#pragma warning(disable : 4996)\n#endif\n\n'
            + cpu + '\n' + gpu + '\n' + ''.join('#undef %s\n' % m for m in macros) +
            '\n#if defined(_MSC_VER)\n#pragma warning(pop)\n#endif\n\n#endif\n')

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('amalgamate: %s, %d bytes, %d lines' % (os.path.relpath(a.out, ROOT), len(text), text.count('\n')))

    pre = os.path.join(ROOT, 'prebuilt', 'tile_spv.inc')
    os.makedirs(os.path.dirname(pre), exist_ok=True)
    with open(pre, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// src/tile.comp compiled by glslc, sha256 of the source %s\n%s\n' % (tile_hash(), spv))
    print('amalgamate: %s, %d bytes' % (os.path.relpath(pre, ROOT), os.path.getsize(pre)))


if __name__ == '__main__':
    main()
